import json
import re
from pathlib import Path
from typing import Dict, List, Optional

from agent.state import Chunk


CORPUS_PATH = (
    Path(__file__).resolve().parent.parent
    / "stub_data"
    / "corpus.json"
)


def _load_corpus() -> List[dict]:
    """
    Load the temporary development corpus.
    Person 2 will later replace this backend with FAISS/Chroma.
    """
    with open(CORPUS_PATH, "r", encoding="utf-8") as file:
        return json.load(file)


def _tokenize(text: str) -> set[str]:
    """
    Convert text into simple lowercase word tokens.
    """
    return set(re.findall(r"[a-zA-Z0-9]+", text.lower()))


def search_corpus(
    query: str,
    k: int = 5,
    filters: Optional[Dict] = None
) -> List[Chunk]:
    """
    Search the temporary corpus using simple keyword overlap.

    Args:
        query:
            Search query generated by the analyst.

        k:
            Maximum number of chunks to return.

        filters:
            Optional filters such as section or document.

    Returns:
        List of matching Chunk objects ordered by relevance.
    """

    corpus = _load_corpus()
    query_tokens = _tokenize(query)

    results = []

    for item in corpus:

        # ---------------------------------------------
        # Apply optional filters
        # ---------------------------------------------
        if filters:
            skip_item = False

            for key, expected_value in filters.items():
                if item.get(key) != expected_value:
                    skip_item = True
                    break

            if skip_item:
                continue

        # ---------------------------------------------
        # Calculate simple keyword-overlap score
        # ---------------------------------------------
        searchable_text = " ".join([
            item.get("section", ""),
            item.get("clause", ""),
            item.get("text", "")
        ])

        document_tokens = _tokenize(searchable_text)

        overlap = query_tokens.intersection(document_tokens)

        if not overlap:
            continue

        score = len(overlap) / max(len(query_tokens), 1)

        result = item.copy()
        result["score"] = score

        results.append(Chunk(**result))

    # Highest score first
    results.sort(
        key=lambda chunk: chunk.score,
        reverse=True
    )

    return results[:k]